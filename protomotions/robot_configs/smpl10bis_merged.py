"""smpl10bis with the 8 socket boxes and the tibial pylon merged into one link.

Same robot as smpl10bis, but those 9 fixed-joint links are a single rigid link,
"socket_assembly" (fixed to prosthetic_assembly2), carrying all their collision shapes and their
combined mass/inertia: 38 links instead of 46, which makes every PhysX step cheaper.
prosthetic_assembly2 is unchanged, so the shank IMU reads the same body.
The assets are generated by protomotions/data/assets/scripts/merge_socket_links.py.

Checkpoints trained on smpl10bis keep their frozen config (and so the 46-link asset); new runs
use this one with --robot-name smpl10bis_merged.
"""
from dataclasses import dataclass, field

from protomotions.robot_configs.base import RobotAssetConfig
from protomotions.robot_configs.smpl10bis import Smpl10bisRobotConfig


@dataclass
class Smpl10bisMergedRobotConfig(Smpl10bisRobotConfig):
    asset: RobotAssetConfig = field(
        default_factory=lambda: RobotAssetConfig(
            asset_file_name="mjcf/smpl_humanoid10bis_merged.xml",
            usd_asset_file_name="usd/smpl_humanoid10bis_merged.usda",
            usd_bodies_root_prim_path="/World/envs/env_.*/Robot/bodies/",
            max_linear_velocity=1000.0,
            max_angular_velocity=100.0,
            angular_damping=0.0,
            linear_damping=0.0,
        )
    )
